import pandas as pd

df = pd.read_excel("GHI_Report (1).xlsx")

attributes = [
    "Economy",
    "Fam",
    "Health",
    "Freedom",
    "H_Score"
]

# Rows 51-56 in the dataset (Python positions 50-55)
selected = df.iloc[50:56][attributes].copy()

# Convert values to numeric
selected = selected.apply(pd.to_numeric, errors="coerce")

# Check missing values
if selected.isnull().values.any():
    raise ValueError(
        "Rows 51-56 contain missing values. Check the selected data."
    )

data = selected.values.tolist()

print("SELECTED ROWS 51-56")
print(selected.to_string(index=False))

n = len(data)
dimensions = len(attributes)

# --------------------------------------------------
# 1. CENTROID
# --------------------------------------------------

centroid = []

for j in range(dimensions):

    total = 0

    for i in range(n):
        total += data[i][j]

    centroid.append(total / n)

print("\nCENTROID")
for j in range(dimensions):
    print(attributes[j], ":", round(centroid[j], 4))


# --------------------------------------------------
# 2. EUCLIDEAN, MANHATTAN AND MINKOWSKI DISTANCES
# --------------------------------------------------

euclidean_distances = []
manhattan_distances = []
minkowski_distances = []

print("\nDISTANCES FROM CENTROID")
print("Point\tEuclidean\tManhattan\tMinkowski (p=3)")

for i in range(n):

    sum_squares = 0
    sum_absolute = 0
    sum_cubes = 0

    for j in range(dimensions):

        difference = data[i][j] - centroid[j]

        sum_squares += difference ** 2
        sum_absolute += abs(difference)
        sum_cubes += abs(difference) ** 3

    euclidean = sum_squares ** 0.5
    manhattan = sum_absolute
    minkowski = sum_cubes ** (1 / 3)

    euclidean_distances.append(euclidean)
    manhattan_distances.append(manhattan)
    minkowski_distances.append(minkowski)

    print(
        i + 51, "\t",
        round(euclidean, 4), "\t\t",
        round(manhattan, 4), "\t\t",
        round(minkowski, 4)
    )


# --------------------------------------------------
# 3. LOWER-TRIANGULAR EUCLIDEAN DISTANCE MATRIX
# --------------------------------------------------

matrix = []

for i in range(n):

    row = []

    for j in range(n):

        if i == j:
            distance = 0.0

        else:

            sum_squares = 0

            for k in range(dimensions):
                difference = data[i][k] - data[j][k]
                sum_squares += difference ** 2

            distance = sum_squares ** 0.5

        row.append(distance)

    matrix.append(row)

print("\nLOWER-TRIANGULAR EUCLIDEAN DISTANCE MATRIX")
print("Rows and columns correspond to records 51-56")

for i in range(n):

    for j in range(n):

        if j <= i:
            print(round(matrix[i][j], 4), end="\t")
        else:
            print("-", end="\t")

    print()


# --------------------------------------------------
# 4. NEAREST AND FARTHEST POINT
# --------------------------------------------------

distance_measures = [
    ("Euclidean", euclidean_distances),
    ("Manhattan", manhattan_distances),
    ("Minkowski (p=3)", minkowski_distances)
]

print("\nNEAREST AND FARTHEST POINTS")

for name, distances in distance_measures:

    nearest = distances.index(min(distances))
    farthest = distances.index(max(distances))

    print("\n", name)
    print("Nearest point: Row", nearest + 51)
    print("Nearest distance:", round(distances[nearest], 4))
    print("Farthest point: Row", farthest + 51)
    print("Farthest distance:", round(distances[farthest], 4))


# --------------------------------------------------
# 5. CHECK WHETHER THE THREE MEASURES AGREE
# --------------------------------------------------

nearest_points = [
    distances.index(min(distances))
    for name, distances in distance_measures
]

farthest_points = [
    distances.index(max(distances))
    for name, distances in distance_measures
]

print("\nAGREEMENT CHECK")

if nearest_points[0] == nearest_points[1] == nearest_points[2]:
    print("All three measures agree on the nearest point.")
else:
    print("The measures do not all agree on the nearest point.")

if farthest_points[0] == farthest_points[1] == farthest_points[2]:
    print("All three measures agree on the farthest point.")
else:
    print("The measures do not all agree on the farthest point.")

