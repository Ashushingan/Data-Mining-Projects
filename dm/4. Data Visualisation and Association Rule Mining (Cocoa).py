# ASSIGNMENT 4 - PART B
# Association Rule Mining using Apriori
# Dataset: Flavors of Cocoa
# Minimum Support = 0.03
# Minimum Confidence = 0.50

import pandas as pd

# --------------------------------------------------
# 1. LOAD DATASET
# --------------------------------------------------

df = pd.read_excel("flavors_of_cocoa (1) (2).xlsx")

minimum_support = 0.03
minimum_confidence = 0.50

total_transactions = len(df)

print("ASSOCIATION RULE MINING")
print("=" * 60)
print("Total reviews:", total_transactions)
print("Minimum support:", minimum_support)
print("Minimum confidence:", minimum_confidence)


# --------------------------------------------------
# 2. FIND TOP 8 COMPANY LOCATIONS
# --------------------------------------------------

location_counts = {}

for location in df["Company Location"]:
    if pd.notna(location):
        if location not in location_counts:
            location_counts[location] = 0

        location_counts[location] += 1

top_locations = sorted(
    location_counts,
    key=location_counts.get,
    reverse=True
)[:8]


# --------------------------------------------------
# 3. CREATE TRANSACTIONS
# Same categories as Assignment 3, Part B
# --------------------------------------------------

transactions = []

for i in range(len(df)):

    transaction = []

    # Company Location
    location = df["Company Location"].iloc[i]

    if pd.notna(location) and location in top_locations:
        transaction.append("Location=" + str(location))
    else:
        transaction.append("Location=Other")

    # Cocoa percentage bands
    cocoa = df["Cocoa Percent"].iloc[i]

    if pd.notna(cocoa):
        cocoa = float(cocoa)

        if cocoa < 0.70:
            transaction.append("Cocoa=<70")
        elif cocoa == 0.70:
            transaction.append("Cocoa=70")
        else:
            transaction.append("Cocoa=>70")
    else:
        transaction.append("Cocoa=Unknown")

    # Rating classes
    # Low: below 3
    # Medium: 3 to below 4
    # High: 4 or above

    rating = df["Rating"].iloc[i]

    if pd.notna(rating):
        rating = float(rating)

        if rating < 3:
            transaction.append("Rating=Low")
        elif rating < 4:
            transaction.append("Rating=Medium")
        else:
            transaction.append("Rating=High")
    else:
        transaction.append("Rating=Unknown")

    # Review periods
    year = df["Review Date"].iloc[i]

    if pd.notna(year):
        year = int(year)

        if 2003 <= year <= 2008:
            transaction.append("Period=2003-08")
        elif 2010 <= year <= 2013:
            transaction.append("Period=2010-13")
        elif 2014 <= year <= 2017:
            transaction.append("Period=2014-17")
        else:
            transaction.append("Period=Other")
    else:
        transaction.append("Period=Other")

    transactions.append(transaction)


print("\nFIRST 5 TRANSACTIONS")

for transaction in transactions[:5]:
    print(transaction)


# --------------------------------------------------
# 4. SUPPORT COUNT
# --------------------------------------------------

def support_count(itemset):

    count = 0

    for transaction in transactions:

        contains_all = True

        for item in itemset:
            if item not in transaction:
                contains_all = False
                break

        if contains_all:
            count += 1

    return count


# --------------------------------------------------
# 5. GENERATE FREQUENT ITEMSETS
# --------------------------------------------------

items = []

for transaction in transactions:
    for item in transaction:
        if item not in items:
            items.append(item)

items.sort()

# Minimum support count rounded up
minimum_count = int(
    minimum_support * total_transactions
)

if minimum_count < minimum_support * total_transactions:
    minimum_count += 1

print("\nMinimum support count:", minimum_count)


def generate_candidates(frequent_itemsets, size):

    candidates = []

    for i in range(len(frequent_itemsets)):
        for j in range(i + 1, len(frequent_itemsets)):

            combined = sorted(
                set(frequent_itemsets[i] + frequent_itemsets[j])
            )

            if len(combined) != size:
                continue

            # Apriori pruning: all subsets must be frequent
            valid = True

            for item in combined:

                subset = []

                for other in combined:
                    if other != item:
                        subset.append(other)

                if subset not in frequent_itemsets:
                    valid = False
                    break

            if valid and combined not in candidates:
                candidates.append(combined)

    return candidates


frequent_itemsets = []

candidates = [[item] for item in items]

# Each transaction has four attributes, so maximum size is 4
for size in range(1, 5):

    print("\n" + "=" * 60)
    print("CANDIDATE C" + str(size))
    print("=" * 60)

    frequent = []

    for candidate in candidates:

        count = support_count(candidate)
        support = count / total_transactions

        print(
            candidate,
            "Count:", count,
            "Support:", round(support, 4)
        )

        if count >= minimum_count:
            frequent.append(candidate)

    print("\nFREQUENT ITEMSETS L" + str(size))

    for itemset in frequent:

        count = support_count(itemset)

        print(
            itemset,
            "Count:", count,
            "Support:",
            round(count / total_transactions, 4)
        )

        frequent_itemsets.append(itemset)

    if len(frequent) == 0 or size == 4:
        break

    candidates = generate_candidates(frequent, size + 1)


# --------------------------------------------------
# 6. GENERATE ALL NON-EMPTY PROPER SUBSETS
# --------------------------------------------------

def proper_nonempty_subsets(itemset):

    ordered_items = sorted(itemset)
    subsets = []

    mask = 1

    while mask < (2 ** len(ordered_items)) - 1:

        subset = []

        for index in range(len(ordered_items)):

            if mask & (1 << index):
                subset.append(ordered_items[index])

        subsets.append(subset)
        mask += 1

    return subsets


# --------------------------------------------------
# 7. GENERATE ASSOCIATION RULES
# --------------------------------------------------

rules = []

for itemset in frequent_itemsets:

    if len(itemset) < 2:
        continue

    union_count = support_count(itemset)

    for antecedent in proper_nonempty_subsets(itemset):

        consequent = []

        for item in itemset:
            if item not in antecedent:
                consequent.append(item)

        antecedent_count = support_count(antecedent)
        consequent_count = support_count(consequent)

        if antecedent_count == 0 or consequent_count == 0:
            continue

        support = union_count / total_transactions

        confidence = union_count / antecedent_count

        consequent_support = (
            consequent_count / total_transactions
        )

        lift = confidence / consequent_support

        if (
            support >= minimum_support
            and confidence >= minimum_confidence
        ):

            rules.append({
                "antecedent": antecedent,
                "consequent": consequent,
                "support": support,
                "confidence": confidence,
                "lift": lift
            })


# --------------------------------------------------
# 8. DISPLAY ALL QUALIFYING RULES
# --------------------------------------------------

print("\n" + "=" * 80)
print("ASSOCIATION RULES")
print("=" * 80)

for rule in rules:

    left = " + ".join(rule["antecedent"])
    right = " + ".join(rule["consequent"])

    print(
        left, "->", right,
        "| Support:", round(rule["support"], 4),
        "| Confidence:", round(rule["confidence"], 4),
        "| Lift:", round(rule["lift"], 4)
    )

print("\nTotal qualifying rules:", len(rules))


# --------------------------------------------------
# 9. TOP 5 RULES BY LIFT
# --------------------------------------------------

rules_by_lift = sorted(
    rules,
    key=lambda rule: rule["lift"],
    reverse=True
)

print("\n" + "=" * 80)
print("TOP 5 RULES BY LIFT")
print("=" * 80)

for i in range(min(5, len(rules_by_lift))):

    rule = rules_by_lift[i]

    print("\nRank:", i + 1)
    print("IF:", " + ".join(rule["antecedent"]))
    print("THEN:", " + ".join(rule["consequent"]))
    print("Support:", round(rule["support"], 4))
    print("Confidence:", round(rule["confidence"], 4))
    print("Lift:", round(rule["lift"], 4))


# --------------------------------------------------
# 10. INTERPRET RULES WITH LIFT > 1 AND LIFT < 1
# --------------------------------------------------

positive_rule = None
negative_rule = None

for rule in rules_by_lift:

    if rule["lift"] > 1 and positive_rule is None:
        positive_rule = rule

    if rule["lift"] < 1:
        negative_rule = rule

print("\n" + "=" * 80)
print("LIFT INTERPRETATION")
print("=" * 80)

if positive_rule is not None:

    print("\nRule with lift > 1:")
    print(
        "IF", " + ".join(positive_rule["antecedent"]),
        "THEN", " + ".join(positive_rule["consequent"])
    )
    print("Lift:", round(positive_rule["lift"], 4))
    print(
        "Interpretation: The antecedent and consequent occur together",
        "more often than expected if they were independent."
    )
else:
    print("No qualifying rule with lift greater than 1 was found.")

if negative_rule is not None:

    print("\nRule with lift < 1:")
    print(
        "IF", " + ".join(negative_rule["antecedent"]),
        "THEN", " + ".join(negative_rule["consequent"])
    )
    print("Lift:", round(negative_rule["lift"], 4))
    print(
        "Interpretation: The antecedent and consequent occur together",
        "less often than expected if they were independent."
    )
else:
    print("No qualifying rule with lift less than 1 was found.")

print("\nLift = 1 indicates statistical independence in terms of")
print("the observed support relationship.")

