# ASSIGNMENT 8 - PART A
# Box Plot Analysis - Cocoa Dataset

import pandas as pd
import matplotlib.pyplot as plt

# Load Cocoa dataset
df = pd.read_excel("flavors_of_cocoa (1) (2).xlsx")

# Convert Cocoa Percent to numeric values
cocoa_values = []

for value in df["Cocoa Percent"]:
    if pd.notna(value):
        if isinstance(value, str):
            value = value.replace("%", "").strip()
            cocoa_values.append(float(value))
        else:
            cocoa_values.append(float(value) * 100)

# Five-number summary using manual calculations
def five_number_summary(values):

    values = sorted(values)
    n = len(values)

    minimum = values[0]
    maximum = values[-1]

    # Median
    if n % 2 == 1:
        median = values[n // 2]
    else:
        median = (values[n // 2 - 1] + values[n // 2]) / 2

    # Q1 and Q3 using median of the two halves
    if n % 2 == 1:
        lower = values[:n // 2]
        upper = values[n // 2 + 1:]
    else:
        lower = values[:n // 2]
        upper = values[n // 2:]

    m = len(lower)

    if m % 2 == 1:
        q1 = lower[m // 2]
        q3 = upper[m // 2]
    else:
        q1 = (lower[m // 2 - 1] + lower[m // 2]) / 2
        q3 = (upper[m // 2 - 1] + upper[m // 2]) / 2

    return minimum, q1, median, q3, maximum


# IQR and outlier detection
def analyse_column(name, values):

    minimum, q1, median, q3, maximum = five_number_summary(values)

    iqr = q3 - q1
    lower_limit = q1 - 1.5 * iqr
    upper_limit = q3 + 1.5 * iqr

    outliers = []

    for value in values:
        if value < lower_limit or value > upper_limit:
            outliers.append(value)

    print("\n", name)
    print("-" * 45)
    print("Minimum:", minimum)
    print("Q1:", q1)
    print("Median:", median)
    print("Q3:", q3)
    print("Maximum:", maximum)
    print("IQR:", iqr)
    print("Lower Bound:", lower_limit)
    print("Upper Bound:", upper_limit)
    print("Number of Outliers:", len(outliers))
    print("Outlier Values:", sorted(outliers))


# Prepare valid rating values
rating_values = []

for value in df["Rating"]:
    if pd.notna(value):
        rating_values.append(float(value))

# Analyse both columns
analyse_column("Rating", rating_values)
analyse_column("Cocoa Percent", cocoa_values)


# --------------------------------------------------
# SIDE-BY-SIDE BOXPLOTS FOR TOP 5 COMPANY LOCATIONS
# --------------------------------------------------

top5_locations = df["Company Location"].value_counts().head(5).index

plot_data = []
plot_labels = []

for location in top5_locations:

    ratings = []

    for i in range(len(df)):
        if df["Company Location"].iloc[i] == location:
            value = df["Rating"].iloc[i]

            if pd.notna(value):
                ratings.append(float(value))

    if len(ratings) > 0:
        plot_data.append(ratings)
        plot_labels.append(location)

plt.figure(figsize=(12, 6))

plt.boxplot(
    plot_data,
    tick_labels=plot_labels,
    showfliers=True
)

plt.title("Rating Distribution for Top 5 Company Locations")
plt.xlabel("Company Location")
plt.ylabel("Rating")
plt.xticks(rotation=30, ha="right")
plt.grid(axis="y", alpha=0.3)
plt.tight_layout()
plt.show()

