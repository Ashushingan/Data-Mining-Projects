# Centroid and Distance Measures - GHI Dataset

import pandas as pd

# Load GHI dataset
df = pd.read_excel("GHI_Report (1).xlsx")

attributes = ["Economy", "Fam", "Health", "Freedom"]

# First six records and required columns
dataframe = df[attributes].head(6).astype(float)

print("FIRST SIX RECORDS")
print(dataframe.to_string(index=False))

# Convert to a list for manual calculations
data = []

for i in range(len(dataframe)):
    row = []

    for attribute in attributes:
        row.append(float(dataframe[attribute].iloc[i]))

    data.append(row)

n = len(data)
dimensions = len(attributes)

# --------------------------------------------------
# 1. CALCULATE CENTROID
# --------------------------------------------------

centroid = []

for j in range(dimensions):

    total = 0

    for i in range(n):
        total += data[i][j]

    centroid.append(total / n)

print("\nCENTROID")
for j in range(dimensions):
    print(attributes[j], ":", round(centroid[j], 4))


# --------------------------------------------------
# 2. DISTANCE FROM CENTROID
# --------------------------------------------------

print("\nDISTANCES FROM CENTROID")
print("-" * 65)
print("Point\tEuclidean\tManhattan\tMinkowski (p=3)")

euclidean_distances = []
manhattan_distances = []
minkowski_distances = []

for i in range(n):

    sum_squares = 0
    sum_absolute = 0
    sum_cubes = 0

    for j in range(dimensions):

        difference = data[i][j] - centroid[j]

        sum_squares += difference ** 2
        sum_absolute += abs(difference)
        sum_cubes += abs(difference) ** 3

    euclidean = sum_squares ** 0.5
    manhattan = sum_absolute
    minkowski = sum_cubes ** (1 / 3)

    euclidean_distances.append(euclidean)
    manhattan_distances.append(manhattan)
    minkowski_distances.append(minkowski)

    print(
        i + 1, "\t",
        round(euclidean, 4), "\t\t",
        round(manhattan, 4), "\t\t",
        round(minkowski, 4)
    )


# --------------------------------------------------
# 3. NEAREST AND FARTHEST POINT
# --------------------------------------------------

distance_measures = [
    ("Euclidean", euclidean_distances),
    ("Manhattan", manhattan_distances),
    ("Minkowski (p=3)", minkowski_distances)
]

print("\nNEAREST AND FARTHEST POINTS")
print("-" * 50)

for name, distances in distance_measures:

    nearest = distances.index(min(distances))
    farthest = distances.index(max(distances))

    print("\n", name)
    print("Nearest Point: Row", nearest + 1)
    print("Nearest Distance:", round(distances[nearest], 4))
    print("Farthest Point: Row", farthest + 1)
    print("Farthest Distance:", round(distances[farthest], 4))


# --------------------------------------------------
# 4. PAIRWISE EUCLIDEAN DISTANCE MATRIX
# --------------------------------------------------

matrix = []

for i in range(n):

    row = []

    for j in range(n):

        if i == j:
            distance = 0.0

        else:
            sum_squares = 0

            for k in range(dimensions):
                difference = data[i][k] - data[j][k]
                sum_squares += difference ** 2

            distance = sum_squares ** 0.5

        row.append(distance)

    matrix.append(row)

print("\nPAIRWISE EUCLIDEAN DISTANCE MATRIX")
print("Lower triangular matrix")

for i in range(n):

    for j in range(n):

        if j <= i:
            print(round(matrix[i][j], 4), end="\t")
        else:
            print("-", end="\t")

    print()

