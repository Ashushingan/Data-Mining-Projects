# PART A: FIVE-NUMBER SUMMARY AND OUTLIERS

import pandas as pd
import matplotlib.pyplot as plt

# Read the Excel dataset
df = pd.read_excel("GHI_Report (1).xlsx")


# Manual sorting: insertion sort
def manual_sort(data):
    a = data[:]

    for i in range(1, len(a)):
        key = a[i]
        j = i - 1

        while j >= 0 and a[j] > key:
            a[j + 1] = a[j]
            j -= 1

        a[j + 1] = key

    return a


# Manual median calculation
def median(data):
    n = len(data)

    if n % 2 == 1:
        return data[n // 2]

    return (data[n // 2 - 1] + data[n // 2]) / 2


# Five-number summary
def five_number_summary(data):
    a = manual_sort(data)
    n = len(a)

    mid = n // 2

    if n % 2 == 0:
        lower = a[:mid]
        upper = a[mid:]
    else:
        lower = a[:mid]
        upper = a[mid + 1:]

    q1 = median(lower)
    med = median(a)
    q3 = median(upper)

    return a[0], q1, med, q3, a[n - 1]


# Calculate results for both columns
columns = ["H_Score", "Economy"]
all_values = {}

for column in columns:
    values = []

    for value in df[column]:
        values.append(float(value))

    all_values[column] = values

    minimum, q1, med, q3, maximum = five_number_summary(values)

    iqr = q3 - q1
    lower_fence = q1 - 1.5 * iqr
    upper_fence = q3 + 1.5 * iqr

    outliers = []

    for value in values:
        if value < lower_fence or value > upper_fence:
            outliers.append(value)

    print("\nColumn:", column)
    print("Minimum:", minimum)
    print("Q1:", q1)
    print("Median:", med)
    print("Q3:", q3)
    print("Maximum:", maximum)
    print("IQR:", iqr)
    print("Lower Fence:", lower_fence)
    print("Upper Fence:", upper_fence)
    print("Outliers:", outliers)


# Draw separate box plots
plt.figure(figsize=(10, 4))

plt.subplot(1, 2, 1)
plt.boxplot(all_values["H_Score"])
plt.title("Box Plot of H_Score")
plt.ylabel("Happiness Score")

plt.subplot(1, 2, 2)
plt.boxplot(all_values["Economy"])
plt.title("Box Plot of Economy")
plt.ylabel("Economy")

plt.tight_layout()
plt.show()

# PART B: K-MEANS CLUSTERING (K = 3)

import math
import matplotlib.pyplot as plt

# Select the four input features
features = ["Economy", "Fam", "Health", "Freedom"]

X = []

for i in range(len(df)):
    point = []

    for feature in features:
        point.append(float(df[feature].iloc[i]))

    X.append(point)

# Store happiness scores separately
h_scores = []

for value in df["H_Score"]:
    h_scores.append(float(value))


# Manual Euclidean distance
def distance(p, q):
    squared_distance = 0.0

    for j in range(len(p)):
        difference = p[j] - q[j]
        squared_distance += difference * difference

    return squared_distance ** 0.5


# Initialize three centroids using existing data points
n = len(X)

centroids = [
    X[0][:],
    X[n // 2][:],
    X[n - 1][:]
]

k = 3
labels = [-1] * n

# K-Means iterations
for iteration in range(100):

    changed = False
    new_labels = []

    # Assign every point to its nearest centroid
    for point in X:
        best_cluster = 0
        best_distance = distance(point, centroids[0])

        for c in range(1, k):
            d = distance(point, centroids[c])

            if d < best_distance:
                best_distance = d
                best_cluster = c

        new_labels.append(best_cluster)

    # Check whether assignments have changed
    for i in range(n):
        if new_labels[i] != labels[i]:
            changed = True

    labels = new_labels

    # Recalculate cluster centers
    new_centroids = []

    for c in range(k):
        center = [0.0] * len(features)
        count = 0

        for i in range(n):
            if labels[i] == c:
                count += 1

                for j in range(len(features)):
                    center[j] += X[i][j]

        if count > 0:
            for j in range(len(features)):
                center[j] /= count

            new_centroids.append(center)
        else:
            # Keep the previous center if a cluster is empty
            new_centroids.append(centroids[c][:])

    centroids = new_centroids

    if not changed:
        break


# Print cluster centers and sizes
print("CLUSTER CENTERS AND SIZES")

for c in range(k):
    count = 0

    for label in labels:
        if label == c:
            count += 1

    print("\nCluster", c + 1)
    print("Center:")

    for j in range(len(features)):
        print(features[j], "=", centroids[c][j])

    print("Cluster size:", count)


# Calculate mean H_Score of each cluster
print("\nMEAN HAPPINESS SCORE")

for c in range(k):
    total = 0.0
    count = 0

    for i in range(n):
        if labels[i] == c:
            total += h_scores[i]
            count += 1

    if count > 0:
        print("Cluster", c + 1, "mean H_Score =", total / count)
    else:
        print("Cluster", c + 1, "is empty")


# Silhouette coefficient
silhouette_values = []

for i in range(n):

    own_cluster = labels[i]

    # Average distance within the same cluster
    own_total = 0.0
    own_count = 0

    for j in range(n):
        if i != j and labels[j] == own_cluster:
            own_total += distance(X[i], X[j])
            own_count += 1

    if own_count == 0:
        silhouette_values.append(0.0)
        continue

    a = own_total / own_count

    # Find the nearest other cluster by average distance
    b = None

    for c in range(k):
        if c == own_cluster:
            continue

        other_total = 0.0
        other_count = 0

        for j in range(n):
            if labels[j] == c:
                other_total += distance(X[i], X[j])
                other_count += 1

        if other_count > 0:
            average_distance = other_total / other_count

            if b is None or average_distance < b:
                b = average_distance

    if b is None:
        silhouette_values.append(0.0)
    else:
        denominator = a

        if b > denominator:
            denominator = b

        if denominator == 0:
            silhouette_values.append(0.0)
        else:
            silhouette_values.append((b - a) / denominator)


# Calculate overall silhouette coefficient manually
total_silhouette = 0.0

for value in silhouette_values:
    total_silhouette += value

silhouette_score = total_silhouette / len(silhouette_values)

print("\nOverall Silhouette Coefficient:", silhouette_score)


# Plot Economy vs Health, colored by cluster
cluster_colors = ["red", "blue", "green"]

plt.figure(figsize=(8, 5))

for c in range(k):
    economy_values = []
    health_values = []

    for i in range(n):
        if labels[i] == c:
            economy_values.append(X[i][0])
            health_values.append(X[i][2])

    plt.scatter(
        economy_values,
        health_values,
        color=cluster_colors[c],
        label="Cluster " + str(c + 1)
    )

plt.xlabel("Economy")
plt.ylabel("Health")
plt.title("K-Means Clustering: Economy vs Health")
plt.legend()
plt.grid(True)
plt.show()

