# 3. MANUAL LOG BASE 2
# --------------------------------------------------

def ln(x):
    if x <= 0:
        return 0

    z = (x - 1) / (x + 1)
    power = z
    result = 0

    for i in range(1, 201):
        result += power / (2 * i - 1)
        power *= z * z

    return 2 * result


def log2(x):
    return ln(x) / ln(2)


# --------------------------------------------------
# 4. ENTROPY
# --------------------------------------------------

def entropy(data):

    if len(data) == 0:
        return 0

    counts = data[TARGET].value_counts()
    total = len(data)
    result = 0

    for count in counts:
        p = count / total

        if p > 0:
            result -= p * log2(p)

    return result


# --------------------------------------------------
# 5. GINI INDEX
# --------------------------------------------------

def gini(data):

    if len(data) == 0:
        return 0

    counts = data[TARGET].value_counts()
    total = len(data)
    result = 1.0

    for count in counts:
        p = count / total
        result -= p * p

    return result


# --------------------------------------------------
# 6. WEIGHTED IMPURITY
# --------------------------------------------------

def weighted_impurity(groups, function):

    total = sum(len(group) for group in groups)

    if total == 0:
        return 0

    result = 0

    for group in groups:
        result += len(group) / total * function(group)

    return result


parent_entropy = entropy(df)
