import pandas as pd
import math

df = pd.read_excel("flavors_of_cocoa (1) (2).xlsx")

# Clean required attributes
df["Company Location"] = (
    df["Company Location"].astype("string").str.strip().str.title()
)

df["Review Date"] = pd.to_numeric(
    df["Review Date"], errors="coerce"
)

df["Rating"] = pd.to_numeric(
    df["Rating"], errors="coerce"
)

df = df.dropna(
    subset=["Company Location", "Review Date", "Rating"]
).reset_index(drop=True)


# Create rating classes
def rating_class(rating):
    if rating < 3:
        return "Low"
    elif rating < 4:
        return "Medium"
    else:
        return "High"


df["Rating_Class"] = df["Rating"].apply(rating_class)


# Group locations into top 5 and Other
top5 = df["Company Location"].value_counts().head(5).index.tolist()

df["Location_Group"] = df["Company Location"].apply(
    lambda x: x if x in top5 else "Other"
)

print("Top 5 locations:", top5)
print("Records used:", len(df))


# Entropy
def entropy(labels):
    counts = {}

    for label in labels:
        counts[label] = counts.get(label, 0) + 1

    result = 0.0
    total = len(labels)

    for count in counts.values():
        p = count / total
        result -= p * math.log2(p)

    return result


# Gini impurity
def gini(labels):
    counts = {}

    for label in labels:
        counts[label] = counts.get(label, 0) + 1

    result = 1.0
    total = len(labels)

    for count in counts.values():
        p = count / total
        result -= p * p

    return result


# Weighted impurity for categorical splits
def categorical_score(data, column):

    parent_entropy = entropy(data["Rating_Class"].tolist())
    parent_gini = gini(data["Rating_Class"].tolist())

    weighted_entropy = 0.0
    weighted_gini = 0.0

    for value in data[column].unique():

        subset = data[data[column] == value]
        weight = len(subset) / len(data)
        labels = subset["Rating_Class"].tolist()

        weighted_entropy += weight * entropy(labels)
        weighted_gini += weight * gini(labels)

    information_gain = parent_entropy - weighted_entropy

    return information_gain, weighted_gini, None


# Evaluate numerical threshold
def numerical_score(data, column):

    values = sorted(data[column].unique())

    best_gain = -1
    best_gini = 1
    best_gain_threshold = None
    best_gini_threshold = None

    parent_entropy = entropy(data["Rating_Class"].tolist())

    for i in range(len(values) - 1):

        threshold = (values[i] + values[i + 1]) / 2

        left = data[data[column] <= threshold]
        right = data[data[column] > threshold]

        if len(left) == 0 or len(right) == 0:
            continue

        left_labels = left["Rating_Class"].tolist()
        right_labels = right["Rating_Class"].tolist()

        weighted_entropy = (
            len(left) / len(data) * entropy(left_labels)
            + len(right) / len(data) * entropy(right_labels)
        )

        weighted_gini = (
            len(left) / len(data) * gini(left_labels)
            + len(right) / len(data) * gini(right_labels)
        )

        gain = parent_entropy - weighted_entropy

        if gain > best_gain:
            best_gain = gain
            best_gain_threshold = threshold

        if weighted_gini < best_gini:
            best_gini = weighted_gini
            best_gini_threshold = threshold

    return (
        best_gain,
        best_gini,
        best_gain_threshold,
        best_gini_threshold
    )


# Compare attributes
results = []

gain, weighted_gini, _ = categorical_score(df, "Location_Group")

results.append({
    "Attribute": "Company Location",
    "Information Gain": gain,
    "Weighted Gini": weighted_gini,
    "Best Threshold": "Categorical split"
})

gain, weighted_gini, gain_threshold, gini_threshold = numerical_score(
    df, "Review Date"
)

results.append({
    "Attribute": "Review Date",
    "Information Gain": gain,
    "Weighted Gini": weighted_gini,
    "Best Threshold": gain_threshold,
    "Best Gini Threshold": gini_threshold
})


