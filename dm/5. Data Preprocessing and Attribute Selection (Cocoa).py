def categorical_split(data, column):

    groups = []

    for value in data[column].unique():
        group = data[data[column] == value]
        groups.append(group)

    child_entropy = weighted_impurity(groups, entropy)
    child_gini = weighted_impurity(groups, gini)

    information_gain = parent_entropy - child_entropy

    return information_gain, child_gini


