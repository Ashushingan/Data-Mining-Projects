# ASSIGNMENT 9 - PART A
# Normalisation - Cocoa Dataset

import pandas as pd
import matplotlib.pyplot as plt

# Load Cocoa dataset
df = pd.read_excel("flavors_of_cocoa (1) (2).xlsx")

# Convert Cocoa Percent to numeric
cocoa = []

for value in df["Cocoa Percent"]:
    if pd.notna(value):
        if isinstance(value, str):
            value = float(value.replace("%", "").strip())
        else:
            value = float(value) * 100

        cocoa.append(value)
    else:
        cocoa.append(None)

df["Cocoa Percent Numeric"] = cocoa

# Prepare valid values for Rating and Cocoa Percent
rating = []
cocoa_percent = []

for value in df["Rating"]:
    if pd.notna(value):
        rating.append(float(value))

for value in df["Cocoa Percent Numeric"]:
    if value is not None:
        cocoa_percent.append(float(value))


# Manual mean
def manual_mean(values):
    total = 0

    for value in values:
        total += value

    return total / len(values)


# Manual population standard deviation
def manual_std(values):
    avg = manual_mean(values)
    total = 0

    for value in values:
        total += (value - avg) ** 2

    return (total / len(values)) ** 0.5


# Min-Max normalisation
def min_max(values):
    smallest = min(values)
    largest = max(values)

    result = []

    for value in values:
        if largest != smallest:
            result.append(
                (value - smallest) / (largest - smallest)
            )
        else:
            result.append(0.0)

    return result


# Z-score normalisation
def z_score(values):
    avg = manual_mean(values)
    sd = manual_std(values)

    result = []

    for value in values:
        if sd != 0:
            result.append((value - avg) / sd)
        else:
            result.append(0.0)

    return result


# Normalise both attributes
rating_minmax = min_max(rating)
rating_zscore = z_score(rating)

cocoa_minmax = min_max(cocoa_percent)
cocoa_zscore = z_score(cocoa_percent)


# Display sample values
print("RATING NORMALISATION")
print("Original | Min-Max | Z-score")

for i in range(min(10, len(rating))):
    print(
        round(rating[i], 3), "|",
        round(rating_minmax[i], 3), "|",
        round(rating_zscore[i], 3)
    )

print("\nCOCOA PERCENT NORMALISATION")
print("Original | Min-Max | Z-score")

for i in range(min(10, len(cocoa_percent))):
    print(
        round(cocoa_percent[i], 3), "|",
        round(cocoa_minmax[i], 3), "|",
        round(cocoa_zscore[i], 3)
    )


# Histograms before and after normalisation
fig, axes = plt.subplots(2, 3, figsize=(15, 8))

axes[0, 0].hist(rating, bins=10, edgecolor="black")
axes[0, 0].set_title("Rating - Original")

axes[0, 1].hist(rating_minmax, bins=10, edgecolor="black")
axes[0, 1].set_title("Rating - Min-Max")

axes[0, 2].hist(rating_zscore, bins=10, edgecolor="black")
axes[0, 2].set_title("Rating - Z-score")

axes[1, 0].hist(cocoa_percent, bins=10, edgecolor="black")
axes[1, 0].set_title("Cocoa Percent - Original")

axes[1, 1].hist(cocoa_minmax, bins=10, edgecolor="black")
axes[1, 1].set_title("Cocoa Percent - Min-Max")

axes[1, 2].hist(cocoa_zscore, bins=10, edgecolor="black")
axes[1, 2].set_title("Cocoa Percent - Z-score")

for ax in axes.flat:
    ax.set_ylabel("Frequency")
    ax.set_xlabel("Value")

plt.tight_layout()
plt.show()


# Verification
print("\nVERIFICATION")

print("Rating Min-Max range:",
      min(rating_minmax), "to", max(rating_minmax))

print("Rating Z-score mean:",
      round(manual_mean(rating_zscore), 6))

print("Rating Z-score standard deviation:",
      round(manual_std(rating_zscore), 6))

print("Cocoa Min-Max range:",
      min(cocoa_minmax), "to", max(cocoa_minmax))

print("Cocoa Z-score mean:",
      round(manual_mean(cocoa_zscore), 6))

print("Cocoa Z-score standard deviation:",
      round(manual_std(cocoa_zscore), 6))

# ASSIGNMENT 9 - PART B
# K-Means Clustering - GHI Dataset

import pandas as pd
import matplotlib.pyplot as plt

from sklearn.preprocessing import StandardScaler
from sklearn.cluster import KMeans
from sklearn.metrics import silhouette_score

# Load GHI dataset
df = pd.read_excel("GHI_Report (1).xlsx")

features = ["Economy", "Fam", "Health", "Freedom"]

# Extract required features and remove incomplete rows
data = df[features].apply(pd.to_numeric, errors="coerce").dropna()

# Z-score normalisation
scaler = StandardScaler()
X = scaler.fit_transform(data)

print("GHI DATASET")
print("Records used:", len(X))
print("Features:", features)

# Test K from 2 to 6
k_values = [2, 3, 4, 5, 6]
sse_values = []
silhouette_values = []
models = []

for k in k_values:

    model = KMeans(
        n_clusters=k,
        random_state=42,
        n_init=10
    )

    labels = model.fit_predict(X)

    sse_values.append(model.inertia_)
    silhouette_values.append(
        silhouette_score(X, labels)
    )

    models.append(model)

    print(
        "K =", k,
        "| SSE =", round(model.inertia_, 4),
        "| Silhouette =", round(silhouette_values[-1], 4)
    )


# Elbow curve: SSE versus K
plt.figure(figsize=(7, 5))
plt.plot(k_values, sse_values, marker="o")
plt.title("Elbow Curve - GHI Dataset")
plt.xlabel("Number of Clusters (K)")
plt.ylabel("SSE")
plt.xticks(k_values)
plt.grid(True)
plt.show()


# Silhouette score versus K
plt.figure(figsize=(7, 5))
plt.plot(k_values, silhouette_values, marker="o")
plt.title("Silhouette Score versus K")
plt.xlabel("Number of Clusters (K)")
plt.ylabel("Silhouette Score")
plt.xticks(k_values)
plt.grid(True)
plt.show()


# Select K with the highest silhouette score
best_index = silhouette_values.index(max(silhouette_values))
best_k = k_values[best_index]
best_model = models[best_index]

print("\nSELECTED K:", best_k)
print("Best silhouette score:",
      round(silhouette_values[best_index], 4))


# Final cluster labels
final_labels = best_model.labels_

# Plot Economy versus Health, coloured by clusters
plt.figure(figsize=(9, 6))

scatter = plt.scatter(
    data["Economy"],
    data["Health"],
    c=final_labels,
    cmap="viridis",
    s=45
)

plt.title("GHI: Economy versus Health by K-Means Cluster")
plt.xlabel("Economy")
plt.ylabel("Health")
plt.legend(*scatter.legend_elements(), title="Cluster")
plt.grid(True, alpha=0.3)
plt.show()


# Show cluster membership
result = data.copy()
result["Cluster"] = final_labels

print("\nCLUSTER COUNTS")
print(result["Cluster"].value_counts().sort_index())

print("\nSAMPLE CLUSTERED RECORDS")
print(result.head(10).to_string(index=False))

