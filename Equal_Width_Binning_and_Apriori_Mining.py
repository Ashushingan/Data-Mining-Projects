# ASSIGNMENT 3 - PART A
# Equal-Width Binning and Smoothing

import pandas as pd

# Load the actual dataset
df = pd.read_excel("flavors_of_cocoa (1) (2).xlsx")

column = "Cocoa Percent"

# Keep valid numeric values with their original row numbers
records = []

for i in range(len(df)):
    value = df[column].iloc[i]

    if pd.notna(value):
        records.append((float(value), i))

# Sort records by Cocoa Percent
records = sorted(records, key=lambda item: item[0])

values = [record[0] for record in records]

minimum = values[0]
maximum = values[-1]

# Divide the range into three equal-width bins
bin_width = (maximum - minimum) / 3

bins = [[], [], []]

for value in values:
    if value <= minimum + bin_width:
        bins[0].append(value)
    elif value <= minimum + 2 * bin_width:
        bins[1].append(value)
    else:
        bins[2].append(value)

# Smooth values using means, medians and boundaries
mean_smoothed = []
median_smoothed = []
boundary_smoothed = []

print("EQUAL-WIDTH BINNING")
print("=" * 55)
print("Minimum Cocoa Percent:", minimum)
print("Maximum Cocoa Percent:", maximum)
print("Bin Width:", bin_width)

for b in range(3):

    bin_values = bins[b]

    print("\nBin", b + 1)
    print("Range:")

    if b == 0:
        print(minimum, "to", minimum + bin_width)
    elif b == 1:
        print(minimum + bin_width, "to", minimum + 2 * bin_width)
    else:
        print(minimum + 2 * bin_width, "to", maximum)

    print("Count:", len(bin_values))

    if len(bin_values) == 0:
        continue

    # Bin mean
    bin_mean = sum(bin_values) / len(bin_values)

    # Bin median
    ordered = sorted(bin_values)
    n = len(ordered)

    if n % 2 == 1:
        bin_median = ordered[n // 2]
    else:
        bin_median = (
            ordered[n // 2 - 1] + ordered[n // 2]
        ) / 2

    # Bin boundaries
    lower = ordered[0]
    upper = ordered[-1]

    for value in bin_values:
        mean_smoothed.append(bin_mean)
        median_smoothed.append(bin_median)

        if value - lower <= upper - value:
            boundary_smoothed.append(lower)
        else:
            boundary_smoothed.append(upper)

# Display 15 sorted records
print("\nFIRST 15 SORTED RECORDS")
print("-" * 85)
print("Original\tBin Mean\tBin Median\tBin Boundaries")

for i in range(min(15, len(values))):
    print(
        round(values[i], 4), "\t\t",
        round(mean_smoothed[i], 4), "\t\t",
        round(median_smoothed[i], 4), "\t\t",
        round(boundary_smoothed[i], 4)
    )

# ASSIGNMENT 3 - PART B
# Apriori Algorithm on Flavors of Cocoa Dataset
# Minimum support = 0.025

import pandas as pd

# Load dataset
df = pd.read_excel("flavors_of_cocoa (1) (2).xlsx")

# --------------------------------------------------
# 1. FIND TOP 8 COMPANY LOCATIONS
# --------------------------------------------------

location_counts = {}

for location in df["Company Location"]:
    if pd.notna(location):
        if location not in location_counts:
            location_counts[location] = 0
        location_counts[location] += 1

# Sort locations by frequency, highest first
top_locations = sorted(
    location_counts,
    key=location_counts.get,
    reverse=True
)[:8]

print("TOP 8 COMPANY LOCATIONS")
for location in top_locations:
    print(location, ":", location_counts[location])


# --------------------------------------------------
# 2. CREATE ONE TRANSACTION PER REVIEW
# --------------------------------------------------

transactions = []

for i in range(len(df)):

    transaction = []

    # Company Location
    location = df["Company Location"].iloc[i]

    if pd.notna(location):
        if location in top_locations:
            transaction.append("Location=" + str(location))
        else:
            transaction.append("Location=Other")
    else:
        transaction.append("Location=Other")

    # Cocoa Percent band
    cocoa = df["Cocoa Percent"].iloc[i]

    if pd.notna(cocoa):
        cocoa = float(cocoa)

        if cocoa < 0.70:
            transaction.append("Cocoa=<70")
        elif cocoa == 0.70:
            transaction.append("Cocoa=70")
        else:
            transaction.append("Cocoa=>70")
    else:
        transaction.append("Cocoa=Unknown")

    # Rating class
    rating = df["Rating"].iloc[i]

    if pd.notna(rating):
        rating = float(rating)

        if rating < 3:
            transaction.append("Rating=Low")
        elif rating < 4:
            transaction.append("Rating=Medium")
        else:
            transaction.append("Rating=High")
    else:
        transaction.append("Rating=Unknown")

    # Review period
    year = df["Review Date"].iloc[i]

    if pd.notna(year):
        year = int(year)

        if 2003 <= year <= 2008:
            transaction.append("Period=2003-2008")
        elif 2010 <= year <= 2013:
            transaction.append("Period=2010-2013")
        elif 2014 <= year <= 2017:
            transaction.append("Period=2014-2017")
        else:
            transaction.append("Period=Other")
    else:
        transaction.append("Period=Other")

    transactions.append(transaction)

total_transactions = len(transactions)

print("\nTOTAL TRANSACTIONS:", total_transactions)
print("\nFIRST 5 TRANSACTIONS")

for transaction in transactions[:5]:
    print(transaction)


# --------------------------------------------------
# 3. SUPPORT COUNT AND SUPPORT
# --------------------------------------------------

min_support = 0.05

# Minimum support count is the ceiling of support * N.
# Integer-only calculation:
min_count = int(min_support * total_transactions)

if min_count < min_support * total_transactions:
    min_count += 1

print("\nMinimum Support:", min_support)
print("Minimum Support Count:", min_count)


def calculate_support(itemset):

    count = 0

    for transaction in transactions:

        found = True

        for item in itemset:
            if item not in transaction:
                found = False
                break

        if found:
            count += 1

    return count


# --------------------------------------------------
# 4. GENERATE CANDIDATES WITH APRIORI PRUNING
# --------------------------------------------------

def generate_candidates(previous_frequent, size):

    candidates = []

    for i in range(len(previous_frequent)):
        for j in range(i + 1, len(previous_frequent)):

            first = previous_frequent[i]
            second = previous_frequent[j]

            combined = sorted(set(first + second))

            if len(combined) != size:
                continue

            # Apriori pruning:
            # Every subset of a candidate must be frequent.
            all_subsets_frequent = True

            for item in combined:

                subset = []

                for other in combined:
                    if other != item:
                        subset.append(other)

                if subset not in previous_frequent:
                    all_subsets_frequent = False
                    break

            if all_subsets_frequent and combined not in candidates:
                candidates.append(combined)

    return candidates


# --------------------------------------------------
# 5. RUN APRIORI FOR L1, L2 AND L3
# --------------------------------------------------

items = []

for transaction in transactions:
    for item in transaction:
        if item not in items:
            items.append(item)

items = sorted(items)

candidates = [[item] for item in items]
previous_frequent = []
frequent_levels = {}

for size in range(1, 4):

    print("\n" + "=" * 60)
    print("CANDIDATE C" + str(size))
    print("=" * 60)

    frequent = []

    for itemset in candidates:

        count = calculate_support(itemset)
        support = count / total_transactions

        print(
            itemset,
            "| Count:", count,
            "| Support:", round(support, 4)
        )

        if count >= min_count:
            frequent.append(itemset)

    print("\nFREQUENT ITEMSETS L" + str(size))
    print("-" * 60)

    for itemset in frequent:

        count = calculate_support(itemset)

        print(
            itemset,
            "| Count:", count,
            "| Support:", round(count / total_transactions, 4)
        )

    frequent_levels[size] = frequent

    previous_frequent = frequent

    if size < 3 and len(frequent) > 0:
        candidates = generate_candidates(
            frequent, size + 1
        )
    else:
        break


# --------------------------------------------------
# 6. VERIFY SUPPORT OF THREE ITEMSETS DIRECTLY
# --------------------------------------------------

print("\n" + "=" * 60)
print("DIRECT SUPPORT VERIFICATION")
print("=" * 60)

verification_itemsets = [
    ["Cocoa=70"],
    ["Rating=High"],
    ["Location=Other", "Cocoa=>70"]
]

for itemset in verification_itemsets:

    count = 0

    for transaction in transactions:

        present = True

        for item in itemset:
            if item not in transaction:
                present = False
                break

        if present:
            count += 1

    support = count / total_transactions

    print("\nItemset:", itemset)
    print("Direct Support Count:", count)
    print("Direct Support:", round(support, 4))
    print("Support Percentage:", round(support * 100, 2), "%")

