# --------------------------------------------------
# 2. GINI IMPURITY
# --------------------------------------------------

def gini(labels):
    if len(labels) == 0:
        return 0.0

    counts = {}

    for label in labels:
        if label not in counts:
            counts[label] = 0
        counts[label] += 1

    impurity = 1.0

    for label in counts:
        probability = counts[label] / len(labels)
        impurity -= probability ** 2

    return impurity


# --------------------------------------------------
# 3. MAJORITY CLASS
# --------------------------------------------------

def majority_class(labels):
    counts = {}

    for label in labels:
        if label not in counts:
            counts[label] = 0
        counts[label] += 1

    best_label = labels[0]
    best_count = 0

    for label in counts:
        if counts[label] > best_count:
            best_count = counts[label]
            best_label = label

    return best_label


# --------------------------------------------------
# 4. SPLIT DATA
# --------------------------------------------------

def split_data(rows, labels, feature_index, threshold):
    left_x, left_y = [], []
    right_x, right_y = [], []

    for i in range(len(rows)):
        if rows[i][feature_index] <= threshold:
            left_x.append(rows[i])
            left_y.append(labels[i])
        else:
            right_x.append(rows[i])
            right_y.append(labels[i])

    return left_x, left_y, right_x, right_y


# --------------------------------------------------
# 5. FIND BEST SPLIT USING GINI
# --------------------------------------------------

def best_split(rows, labels):
    best_score = None
    best_feature = None
    best_threshold = None

    for feature_index in range(len(features)):

        unique_values = []

        for row in rows:
            value = row[feature_index]

            if value not in unique_values:
                unique_values.append(value)

        unique_values = sorted(unique_values)

        for i in range(len(unique_values) - 1):

            threshold = (
                unique_values[i] + unique_values[i + 1]
            ) / 2

            lx, ly, rx, ry = split_data(
                rows, labels, feature_index, threshold
            )

            if len(ly) == 0 or len(ry) == 0:
                continue

            weighted_gini = (
                len(ly) / len(labels) * gini(ly)
                + len(ry) / len(labels) * gini(ry)
            )

            if best_score is None or weighted_gini < best_score:
                best_score = weighted_gini
                best_feature = feature_index
                best_threshold = threshold

    return best_feature, best_threshold, best_score


# --------------------------------------------------
# 6. BUILD DECISION TREE
# --------------------------------------------------

def build_tree(rows, labels, depth, max_depth):

    node = {
        "prediction": majority_class(labels),
        "feature": None,
        "threshold": None,
        "left": None,
        "right": None
    }

    if gini(labels) == 0 or depth >= max_depth:
        return node

    feature_index, threshold, score = best_split(rows, labels)

    if feature_index is None:
        return node

    lx, ly, rx, ry = split_data(
        rows, labels, feature_index, threshold
    )

    node["feature"] = feature_index
    node["threshold"] = threshold

    node["left"] = build_tree(
        lx, ly, depth + 1, max_depth
    )

    node["right"] = build_tree(
        rx, ry, depth + 1, max_depth
    )

    return node


# --------------------------------------------------
# 7. PRINT TREE RULES
# --------------------------------------------------

def print_tree(node, depth=0):

    indent = "    " * depth

    if node["feature"] is None:
        print(indent + "Predict:", node["prediction"])
        return

    name = features[node["feature"]]
    threshold = node["threshold"]

    print(indent + name + " <= " + str(round(threshold, 3)))
    print(indent + "  True:")
    print_tree(node["left"], depth + 1)

    print(indent + "  False:")
    print_tree(node["right"], depth + 1)


# --------------------------------------------------
# 8. PREDICT CLASS
# --------------------------------------------------

def predict(node, row):

    if node["feature"] is None:
        return node["prediction"]

    if row[node["feature"]] <= node["threshold"]:
        return predict(node["left"], row)

    return predict(node["right"], row)


