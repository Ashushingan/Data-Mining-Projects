# Manual mean calculation
def mean(data):
    total = 0.0

    for x in data:
        total += x

    return total / len(data)


# Manual population standard deviation
def std_dev(data):
    avg = mean(data)
    squared_total = 0.0

    for x in data:
        squared_total += (x - avg) ** 2

    return (squared_total / len(data)) ** 0.5


